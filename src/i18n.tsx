const SUPPORTED: Array<{ code: LangCode; name: string }> = LANGS
  .map((code) => ({ code, name: getLanguageLabel(code) }))

// Real translations for a few languages; others fall back to English until expanded

const DICT: Record<string, Record<string, string>> = {
  en: { ...DICT_BASE },
  ...GENERATED_DICT,
}

// For all other locales not explicitly translated, fall back to English base
for (const s of SUPPORTED) {
  if (!DICT[s.code]) DICT[s.code] = { ...DICT_BASE }
}

const Ctx = createContext<I18nContextType | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const missingKeys = React.useRef<Set<string>>(new Set())
  const translateDom = React.useRef(createDomTranslator())
  const defaultLang = (() => {
    try {
      const saved = localStorage.getItem('oc.lang') as LangCode | null
      if (saved && (SUPPORTED.find(s => s.code === saved))) return saved
      for (const locale of navigator.languages || [navigator.language || 'en']) {
        const exact = SUPPORTED.find(s => s.code.toLowerCase() === locale.toLowerCase())
        if (exact) return exact.code
        const base = locale.split('-')[0].toLowerCase()
        const match = SUPPORTED.find(s => s.code.toLowerCase() === base)
          || SUPPORTED.find(s => s.code.split('-')[0].toLowerCase() === base)
        if (match) return match.code
      }
      return 'en' as LangCode
    } catch { return 'en' as LangCode }
  })()
  const [lang, setLangState] = useState<LangCode>(defaultLang)

  useEffect(() => {
    try { document.documentElement.setAttribute('lang', lang) } catch {}
    try { localStorage.setItem('oc.lang', lang) } catch {}
  }, [lang])

  useEffect(() => {
    if (typeof document === 'undefined') return
    const map = lang === 'en' ? new Map<string, string>() : buildLiteralMap(lang)
    const options: MutationObserverInit = {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ['title', 'aria-label', 'placeholder', 'alt'],
    }
    const observer = new MutationObserver(() => {
      // Do not observe our own writes and repeatedly translate the same nodes.
      observer.disconnect()
      try { translateDom.current(document.body, map) }
      finally { observer.observe(document.body, options) }
    })
    translateDom.current(document.body, map)
    observer.observe(document.body, options)
    return () => observer.disconnect()
  }, [lang])

  const t = useMemo(() => (key: string) => {
    const ldict = DICT[lang] || DICT.en
    const value = ldict[key] || DICT.en[key]
    if (!value && import.meta.env.DEV && !missingKeys.current.has(key)) {
      missingKeys.current.add(key)
      // eslint-disable-next-line no-console
      console.warn(`[i18n] Missing key: ${key}`)
    }
    return value || key
  }, [lang])

  const value: I18nContextType = {
    lang,
    setLang: (code) => setLangState(code),
    t,
    supported: SUPPORTED,
  }

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

