type LanguageListEntry = { name: string; charset?: string }
const LANGUAGE_LIST = languageList as Record<string, LanguageListEntry>

const getLanguageListName = (code: LangCode) => {
  const key = code.replace('-', '_')
  const direct = LANGUAGE_LIST[key]?.name
  if (direct) return direct
  const base = LANGUAGE_LIST[key.split('_')[0]]?.name
  return base || ''
}

const getDisplayName = (code: LangCode, locale: string) => {
  try {
    const dn = new Intl.DisplayNames([locale], { type: 'language' })
    return dn.of(code) || code
  } catch {
    return code
  }
}

const isCorruptedLabel = (label: string) => {
  if (!label) return true
  if (label.includes('\uFFFD')) return true
  if (/\?{2,}/.test(label)) return true
  return false
}

const getLanguageLabel = (code: LangCode) => {
  const listName = getLanguageListName(code)
  if (listName && !isCorruptedLabel(listName)) return listName
  const english = getDisplayName(code, 'en')
  const native = getDisplayName(code, code)
  const safeEnglish = isCorruptedLabel(english) ? code : english
  if (!isCorruptedLabel(native) && native && native != safeEnglish) {
    return `${safeEnglish} (${native})`
  }
  return safeEnglish
}

const buildLiteralMap = (lang: LangCode) => {
  const target = DICT[lang] || DICT.en
  const map = new Map<string, string>()
  for (const [key, english] of Object.entries(DICT_BASE)) {
    const translated = target[key] || DICT.en[key]
    if (english && translated) map.set(english, translated)
  }
  return map
}

